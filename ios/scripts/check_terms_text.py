#!/usr/bin/env python3
"""Keeps the iPhone app's Terms identical to the one source of the text (#440).

frontend/src/legal/terms.json is the only copy of the Terms. The web renders it
on /terms and in TermsModal.js; the app bundles it as Swift in
ios/Loore/Features/Onboarding/TermsText.swift, which this script generates.

Usage, from the repo root:
  python3 ios/scripts/check_terms_text.py            # exit 1 if TermsText.swift is not
                                                      # what terms.json generates
  python3 ios/scripts/check_terms_text.py --write    # regenerate TermsText.swift
  python3 ios/scripts/check_terms_text.py --release  # also exit 1 while a [PLACEHOLDER]
                                                      # is left in terms.json or privacy.json

The check also validates both JSON files: known block types, balanced **bold**,
and links the app can open (https:// or mailto:).
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
LEGAL = ROOT / "frontend/src/legal"
TERMS = LEGAL / "terms.json"
PRIVACY = LEGAL / "privacy.json"
SWIFT = ROOT / "ios/Loore/Features/Onboarding/TermsText.swift"

TEXT_BLOCKS = ("title", "sectionTitle", "subheading", "paragraph", "footnote")
LIST_BLOCKS = ("bullets", "plainList", "quoteBox")
PLACEHOLDER = re.compile(r"\[[A-Z][A-Z0-9 /&.,'-]+\](?!\()")
LINK = re.compile(r"\]\(([^)]*)\)")

HEADER = """\
// GENERATED by ios/scripts/check_terms_text.py --write from
// frontend/src/legal/terms.json, the one source of the Terms (#440). Do not edit:
// change terms.json, then run the script. CI fails when the two differ.
//
// Inline Markdown marks bold (`**…**`), italic (`*…*`) and links, as on the web.
// The block types are `TermsBlock`, in TermsView.swift.

enum TermsText {
"""


def swift_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def swift_list(items, indent):
    pad = " " * indent
    lines = "".join(f"{pad}    {swift_string(item)},\n" for item in items)
    return "[\n" + lines + pad + "]"


def swift_block(block):
    kind = block["type"]
    if kind in TEXT_BLOCKS:
        return f".{kind}({swift_string(block['text'])})"
    if kind == "bullets" or kind == "plainList" or kind == "quoteBox":
        return f".{kind}({swift_list(block['items'], 8)})"
    if kind == "summaryBox":
        return (f".summaryBox(title: {swift_string(block['title'])}, "
                f"items: {swift_list(block['items'], 8)})")
    if kind == "table":
        rows = "".join(
            "            [" + ", ".join(swift_string(c) for c in row) + "],\n"
            for row in block["rows"])
        header = "[" + ", ".join(swift_string(c) for c in block["header"]) + "]"
        return f".table(header: {header}, rows: [\n{rows}        ])"
    if kind == "rule":
        return ".rule"
    raise ValueError(f"unknown block type {kind!r}")


def generate(doc):
    body = "".join(f"        {swift_block(b)},\n" for b in doc["blocks"])
    return (
        HEADER
        + f"    static let version = {swift_string(doc['version'])}\n\n"
        + "    static let blocks: [TermsBlock] = [\n" + body + "    ]\n\n"
        + "    /// Shown under the text, above \"I Agree\" (not on the public page).\n"
        + f"    static let acceptNote = {swift_string(doc['acceptNote'])}\n"
        + "}\n"
    )


def texts(doc):
    """Every string of a document, with where it is."""
    for i, block in enumerate(doc["blocks"]):
        for key, value in block.items():
            if key in ("type", "id"):
                continue
            values = value if isinstance(value, list) else [value]
            for v in values:
                for cell in (v if isinstance(v, list) else [v]):
                    yield f"block {i} ({block['type']})", cell
    if "acceptNote" in doc:
        yield "acceptNote", doc["acceptNote"]


def validate(name, doc):
    problems = []
    known = set(TEXT_BLOCKS) | set(LIST_BLOCKS) | {"summaryBox", "table", "rule"}
    for i, block in enumerate(doc.get("blocks", [])):
        if block.get("type") not in known:
            problems.append(f"{name}: block {i} has unknown type {block.get('type')!r}")
    for where, text in texts(doc):
        if not isinstance(text, str):
            problems.append(f"{name}: {where} is not text")
            continue
        if text.count("**") % 2:
            problems.append(f"{name}: {where} has unbalanced ** in: {text[:60]}")
        for url in LINK.findall(text):
            if not url.startswith(("https://", "mailto:")):
                problems.append(f"{name}: {where} links to {url!r}; use https:// or mailto:")
    return problems


def placeholders(doc):
    found = []
    for _, text in texts(doc):
        for m in PLACEHOLDER.findall(text):
            if m not in found:
                found.append(m)
    return found


def main(argv):
    terms = json.loads(TERMS.read_text(encoding="utf-8"))
    privacy = json.loads(PRIVACY.read_text(encoding="utf-8"))
    problems = validate("terms.json", terms) + validate("privacy.json", privacy)
    if problems:
        print("\n".join(problems))
        return 1

    expected = generate(terms)
    if "--write" in argv:
        SWIFT.write_text(expected, encoding="utf-8")
        print(f"Wrote {SWIFT.relative_to(ROOT)} from terms.json (version {terms['version']}).")
    elif SWIFT.read_text(encoding="utf-8") != expected:
        print(f"{SWIFT.relative_to(ROOT)} is not what terms.json generates.\n"
              "Run: python3 ios/scripts/check_terms_text.py --write")
        return 1
    else:
        print(f"TermsText.swift matches terms.json (version {terms['version']}, "
              f"{len(terms['blocks'])} blocks).")

    if "--release" in argv:
        left = placeholders(terms) + [p for p in placeholders(privacy) if p not in placeholders(terms)]
        if left:
            print("Placeholders left: " + ", ".join(left))
            return 1
        print("No placeholders left.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
